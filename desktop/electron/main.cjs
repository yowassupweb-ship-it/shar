function registerWindowControls(mainWindow) {
  ipcMain.removeHandler('window:minimize');
  ipcMain.removeHandler('window:toggle-maximize');
  ipcMain.removeHandler('window:close');
  ipcMain.removeHandler('window:is-maximized');
  ipcMain.removeHandler('window:open-external');
  ipcMain.removeHandler('startup:get');
  ipcMain.removeHandler('startup:set');

  ipcMain.handle('window:minimize', () => {
    if (!mainWindow.isDestroyed()) {
      mainWindow.minimize();
    }
  });

  ipcMain.handle('window:toggle-maximize', () => {
    if (mainWindow.isDestroyed()) return false;

    if (mainWindow.isMaximized()) {
      mainWindow.unmaximize();
      return false;
    }

    mainWindow.maximize();
    return true;
  });

  ipcMain.handle('window:close', () => {
    if (!mainWindow.isDestroyed()) {
      mainWindow.close();
    }
  });

  ipcMain.handle('window:is-maximized', () => {
    if (mainWindow.isDestroyed()) return false;
    return mainWindow.isMaximized();
  });

  ipcMain.handle('window:open-external', (_, url) => {
    if (typeof url === 'string' && url.trim()) {
      return shell.openExternal(url);
    }

    return shell.openExternal(resolveRemoteUrl());
  });

  ipcMain.handle('startup:get', () => {
    if (process.platform !== 'win32') {
      return { supported: false, openAtLogin: false };
    }

    const settings = app.getLoginItemSettings();
    return {
      supported: true,
      openAtLogin: Boolean(settings.openAtLogin),
      preferred: getAutoLaunchPreference(),
    };
  });

  ipcMain.handle('startup:set', (_event, openAtLogin) => {
    if (process.platform !== 'win32') {
      return { supported: false, openAtLogin: false };
    }

    const enabled = setAutoLaunchPreference(Boolean(openAtLogin));
    return {
      supported: true,
      openAtLogin: enabled,
      preferred: enabled,
    };
  });

  ipcMain.handle('window:reload', () => {
    if (!mainWindow.isDestroyed()) {
      mainWindow.reload();
    }
  });

  ipcMain.handle('window:zoom-in', () => {
    if (!mainWindow.isDestroyed()) {
      const currentZoom = mainWindow.webContents.getZoomFactor();
      mainWindow.webContents.setZoomFactor(Math.min(currentZoom + 0.1, 3.0));
      return Math.round(mainWindow.webContents.getZoomFactor() * 100);
    }
    return 100;
  });

  ipcMain.handle('window:zoom-out', () => {
    if (!mainWindow.isDestroyed()) {
      const currentZoom = mainWindow.webContents.getZoomFactor();
      mainWindow.webContents.setZoomFactor(Math.max(currentZoom - 0.1, 0.5));
      return Math.round(mainWindow.webContents.getZoomFactor() * 100);
    }
    return 100;
  });

  ipcMain.handle('window:set-zoom', (_, zoomPercent) => {
    if (!mainWindow.isDestroyed()) {
      const zoomFactor = zoomPercent / 100;
      mainWindow.webContents.setZoomFactor(Math.max(0.5, Math.min(zoomFactor, 3.0)));
      return Math.round(mainWindow.webContents.getZoomFactor() * 100);
    }
    return 100;
  });

  // Document viewer (docx/pdf) third column. Always make room by GROWING the
  // window rather than squeezing the chat: growing to the right where there's
  // space, otherwise sliding the window left first (and, failing that, filling
  // the work area). Squeezing the chat into a narrow strip was the worse
  // trade-off — this is what "лучше насильно расширять окно" settled.
  // Returns true when the window absorbed the panel's width, so the renderer
  // only has to reserve space itself in the rare case nothing could grow.
  let widthBeforeDocPanel = null;
  let posBeforeDocPanel = null;
  const DOC_PANEL_WIDTH = 420;
  ipcMain.handle('window:set-document-panel-open', (_, open) => {
    if (mainWindow.isDestroyed()) return false;
    const { screen } = require('electron');
    const [w, h] = mainWindow.getSize();
    const [x, y] = mainWindow.getPosition();
    if (open) {
      const workArea = screen.getDisplayMatching({ x, y, width: w, height: h }).workArea;
      const roomToRight = (workArea.x + workArea.width) - (x + w);
      if (widthBeforeDocPanel == null) { widthBeforeDocPanel = w; posBeforeDocPanel = { x, y }; }

      if (roomToRight >= DOC_PANEL_WIDTH) {
        mainWindow.setSize(w + DOC_PANEL_WIDTH, h);
        return true;
      }
      // Not enough room on the right — shift left by the shortfall if the
      // window can move that far, then grow.
      const shortfall = DOC_PANEL_WIDTH - Math.max(0, roomToRight);
      const roomToLeft = x - workArea.x;
      if (roomToLeft >= shortfall) {
        mainWindow.setPosition(x - shortfall, y);
        mainWindow.setSize(w + DOC_PANEL_WIDTH, h);
        return true;
      }
      // Can't fit even by moving: take the whole work-area width. Only counts
      // as "widened" if that actually gained the panel its full width.
      const maxWidth = workArea.width;
      mainWindow.setPosition(workArea.x, y);
      mainWindow.setSize(maxWidth, h);
      return (maxWidth - w) >= DOC_PANEL_WIDTH;
    }
    if (widthBeforeDocPanel != null) {
      mainWindow.setSize(widthBeforeDocPanel, h);
      if (posBeforeDocPanel) mainWindow.setPosition(posBeforeDocPanel.x, posBeforeDocPanel.y);
      widthBeforeDocPanel = null;
      posBeforeDocPanel = null;
    }
    return false;
  });

  // Save-as dialog for the docx viewer's export (see DocxViewer.tsx) — data
  // arrives as an ArrayBuffer over IPC (structured-clone friendly) and is
  // written directly, no temp file/round-trip needed.
  ipcMain.handle('file:save', async (_, data, suggestedName) => {
    if (mainWindow.isDestroyed()) return false;
    const { canceled, filePath } = await dialog.showSaveDialog(mainWindow, {
      defaultPath: suggestedName || 'document.docx',
      filters: [{ name: 'Word Document', extensions: ['docx'] }],
    });
    if (canceled || !filePath) return false;
    const fs = require('fs');
    fs.writeFileSync(filePath, Buffer.from(data));
    return true;
  });

  ipcMain.handle('window:get-zoom', () => {
    if (!mainWindow.isDestroyed()) {
      return Math.round(mainWindow.webContents.getZoomFactor() * 100);
    }
    return 100;
  });
}

function registerInputContextMenu(mainWindow) {
  if (!mainWindow || mainWindow.isDestroyed()) return;

  mainWindow.webContents.on('context-menu', (_event, params) => {
    if (!params) return;

    const hasSelection = typeof params.selectionText === 'string' && params.selectionText.trim().length > 0;
    const inputFieldType = typeof params.inputFieldType === 'string' ? params.inputFieldType : 'none';
    const isInputField = inputFieldType !== 'none';
    const hasEditFlags = Boolean(
      params.editFlags?.canUndo ||
      params.editFlags?.canRedo ||
      params.editFlags?.canCut ||
      params.editFlags?.canCopy ||
      params.editFlags?.canPaste ||
      params.editFlags?.canSelectAll
    );
    const isEditableContext = Boolean(params.isEditable || isInputField || hasEditFlags);

    if (!isEditableContext && !hasSelection) return;

    // `role` alone renders Electron/Chromium's built-in EN labels regardless of
    // app locale on Windows — an explicit `label` overrides just the text while
    // `role` still supplies the actual undo/cut/copy/etc behavior. (Native
    // context menus are OS-rendered — there's no Menu API knob for font size;
    // that follows the Windows system menu font, not something this app sets.)
    const menu = Menu.buildFromTemplate([
      { role: 'undo', label: 'Отменить', enabled: Boolean(params.editFlags?.canUndo) },
      { role: 'redo', label: 'Повторить', enabled: Boolean(params.editFlags?.canRedo) },
      { type: 'separator' },
      { role: 'cut', label: 'Вырезать', enabled: Boolean(params.editFlags?.canCut) },
      { role: 'copy', label: 'Копировать', enabled: Boolean(params.editFlags?.canCopy || hasSelection) },
      { role: 'paste', label: 'Вставить', enabled: Boolean(params.editFlags?.canPaste || isEditableContext) },
      { role: 'selectAll', label: 'Выделить всё', enabled: Boolean(params.editFlags?.canSelectAll || isEditableContext) },
    ]);

    menu.popup({ window: mainWindow });
  });
}

// Notification system
let activeNotifications = [];
let mainWindowRef = null;
const NOTIFICATION_WIDTH = 376;
const NOTIFICATION_COMPACT_HEIGHT = 76;
const NOTIFICATION_DETAILED_HEIGHT = 112;
const NOTIFICATION_MARGIN = 8;
const NOTIFICATION_GAP = 0;
// Native toast is deliberately short and non-blocking: it stays above all windows
// for ten seconds, then asks its renderer to fade out before the BrowserWindow is
// destroyed.  Destroying it immediately skipped the CSS animation and looked like a
// random disappearance.
const NOTIFICATION_AUTO_CLOSE_MS = 10000;
const NOTIFICATION_FADE_OUT_MS = 280;
const MAX_ACTIVE_NOTIFICATIONS = 4;

function activateNotificationTarget(mainWindow, clickData) {
  if (!mainWindow || mainWindow.isDestroyed()) return;

  mainWindow.show();
  if (mainWindow.isMinimized()) {
    mainWindow.restore();
  }
  mainWindow.focus();

  if (clickData && typeof clickData.url === 'string' && clickData.url.trim()) {
    mainWindow.webContents.send('open-route', clickData.url);
  }

  if (clickData && clickData.chatId) {
    mainWindow.webContents.send('open-chat', clickData.chatId);
  }
}

function showNativeNotification(data, mainWindow) {
  if (!Notification.isSupported()) {
    return false;
  }

  const iconPath = process.platform === 'win32'
    ? path.join(__dirname, 'icon.png')
    : path.join(__dirname, 'icon.png');

  const title = data?.senderName || data?.title || 'Shar OS';
  const bodyParts = [];
  if (data?.chatName) {
    bodyParts.push(String(data.chatName));
  } else if (data?.subtitle) {
    bodyParts.push(String(data.subtitle));
  }
  if (data?.message) {
    bodyParts.push(String(data.message));
  }
  const body = bodyParts.join('\n');
  const subtitle = data?.subtitle || data?.chatName || '';
  const notification = new Notification({
    title,
    subtitle,
    body,
    icon: iconPath,
    silent: false,
    timeoutType: 'default',
  });

  notification.on('click', () => {
    activateNotificationTarget(mainWindow, data);
  });

  notification.show();
  return true;
}

function createNotificationWindow(data, mainWindow) {
  if (String(data?.kind || '').toLowerCase() === 'message' && !claimMessageCard(data)) return null;
  // The update card is from Shar OS itself: without a picture notification.html
  // seeded a DiceBear face off "Shar OS", which read as some random user.
  if (data?.updateAction && !data.avatar) {
    data = { ...data, avatar: require('url').pathToFileURL(path.join(__dirname, 'icon.png')).href };
  }
  const { screen } = require('electron');
  const primaryDisplay = screen.getPrimaryDisplay();
  const { width: screenWidth, height: screenHeight } = primaryDisplay.workAreaSize;

  activeNotifications = activeNotifications.filter(win => win && !win.isDestroyed() && !win.__isClosing);

  // Keep stack compact like Telegram desktop.
  while (activeNotifications.length >= MAX_ACTIVE_NOTIFICATIONS) {
    const oldest = activeNotifications[0];
    closeNotification(oldest);
    activeNotifications = activeNotifications.filter(win => win && !win.isDestroyed());
  }
  
  // Вычисляем позицию (правый нижний угол с учетом других уведомлений)
  const messageLength = String(data?.message || '').trim().length;
  const isDetailed = data?.compact === false || data?.detailed === true ||
    ['task', 'event', 'system'].includes(String(data?.kind || '').toLowerCase()) ||
    messageLength > 72;
  const notificationHeight = isDetailed ? NOTIFICATION_DETAILED_HEIGHT : NOTIFICATION_COMPACT_HEIGHT;
  const baseX = screenWidth - NOTIFICATION_WIDTH - NOTIFICATION_MARGIN;
  const baseY = screenHeight - notificationHeight - NOTIFICATION_MARGIN;
  
  const notificationWindow = new BrowserWindow({
    width: NOTIFICATION_WIDTH,
    height: notificationHeight,
    x: baseX,
    y: baseY,
    frame: false,
    transparent: true,
    alwaysOnTop: true,
    skipTaskbar: true,
    resizable: false,
    minimizable: false,
    maximizable: false,
    closable: true,
    focusable: false,
    show: false,
    webPreferences: {
      nodeIntegration: true,
      contextIsolation: false,
    },
  });
  notificationWindow.__notificationHeight = notificationHeight;
  // Lets the card be dismissed once its chat is open and in focus (see 'realtime:context').
  notificationWindow.__chatId = (() => { const raw = String(data?.chatId || '').trim(); try { return decodeURIComponent(raw); } catch { return raw; } })();
  notificationWindow.__isMessageCard = String(data?.kind || '').toLowerCase() === 'message';

  notificationWindow.setVisibleOnAllWorkspaces(true, { visibleOnFullScreen: true });
  notificationWindow.setAlwaysOnTop(true, 'screen-saver', 1);

  notificationWindow.loadFile(path.join(__dirname, 'notification.html'));

  notificationWindow.once('ready-to-show', () => {
    let appOrigin = '';
    try {
      const mainUrl = mainWindow?.webContents?.getURL?.() || '';
      if (mainUrl) {
        appOrigin = new URL(mainUrl).origin;
      }
    } catch {
      appOrigin = '';
    }

    // showInactive: a card must never take focus from the window being typed in —
    // that blur is exactly what made the next message look "unattended".
    notificationWindow.showInactive();
    notificationWindow.webContents.send('notification-data', {
      ...data,
      appOrigin,
      displayMode: isDetailed ? 'detailed' : 'compact',
    });
  });

  const autoCloseTimer = setTimeout(() => {
    closeNotification(notificationWindow);
  }, NOTIFICATION_AUTO_CLOSE_MS);

  const notificationClickHandler = (event, clickData) => {
    if (!notificationWindow || notificationWindow.isDestroyed()) return;
    if (event.sender !== notificationWindow.webContents) return;

    // У уведомления о новой версии нет чата, куда переходить: клик по нему —
    // то же действие, что и кнопка «Обновить».
    if (data && data.updateAction) {
      closeNotification(notificationWindow);
      installUpdateNow();
      return;
    }

    activateNotificationTarget(mainWindow, clickData);

    closeNotification(notificationWindow);
  };

  const notificationCloseHandler = (event) => {
    if (!notificationWindow || notificationWindow.isDestroyed()) return;
    if (event.sender !== notificationWindow.webContents) return;
    closeNotification(notificationWindow);
  };

  const notificationDismissedHandler = (event) => {
    if (!notificationWindow || notificationWindow.isDestroyed()) return;
    if (event.sender !== notificationWindow.webContents) return;
    try { notificationWindow.destroy(); } catch { /* ignore */ }
  };

  ipcMain.on('notification-click', notificationClickHandler);
  ipcMain.on('notification-close', notificationCloseHandler);
  ipcMain.on('notification-dismissed', notificationDismissedHandler);

  activeNotifications.push(notificationWindow);
  repositionNotifications();
  
  notificationWindow.on('closed', () => {
    ipcMain.removeListener('notification-click', notificationClickHandler);
    ipcMain.removeListener('notification-close', notificationCloseHandler);
    ipcMain.removeListener('notification-dismissed', notificationDismissedHandler);
    clearTimeout(autoCloseTimer);
    const index = activeNotifications.indexOf(notificationWindow);
    if (index > -1) {
      activeNotifications.splice(index, 1);
    }
    repositionNotifications();
  });

  return notificationWindow;
}

function closeNotification(notificationWindow) {
  if (!notificationWindow || notificationWindow.isDestroyed()) return;
  if (notificationWindow.__isClosing) return;

  notificationWindow.__isClosing = true;
  activeNotifications = activeNotifications.filter(win => win && win !== notificationWindow && !win.isDestroyed() && !win.__isClosing);
  repositionNotifications();

  // Let notification.html play the exit transition.  A timeout remains as a
  // fail-safe for a renderer that never reached ready-to-show or crashed.
  try { notificationWindow.webContents.send('notification-closing'); } catch { /* ignore */ }
  setTimeout(() => {
    try {
      if (!notificationWindow.isDestroyed()) notificationWindow.destroy();
    } catch { /* ignore */ }
  }, NOTIFICATION_FADE_OUT_MS + 120);
}

function repositionNotifications() {
  const { screen } = require('electron');
  const primaryDisplay = screen.getPrimaryDisplay();
  const { width: screenWidth, height: screenHeight } = primaryDisplay.workAreaSize;

  activeNotifications = activeNotifications.filter(notification => notification && !notification.isDestroyed() && !notification.__isClosing);

  const baseX = screenWidth - NOTIFICATION_WIDTH - NOTIFICATION_MARGIN;
  let offsetY = NOTIFICATION_MARGIN;
  activeNotifications.forEach((notification) => {
    if (!notification.isDestroyed()) {
      const height = notification.__notificationHeight || NOTIFICATION_COMPACT_HEIGHT;
      const yPosition = screenHeight - offsetY - height;
      
      notification.setBounds({
        x: baseX,
        y: yPosition,
        width: NOTIFICATION_WIDTH,
        height,
      });
      offsetY += height + NOTIFICATION_GAP;
    }
  });
}

// ── Call Window ─────────────────────────────────────────────────────────────
let callWindowRef = null;
// Explicit state instead of trusting callWindowRef.isMinimized() — on this window's
// exact config (frameless, transparent, alwaysOnTop) Windows has been observed
// reporting it minimized immediately after creation, with no minimize ever
// happening, which made the island take over instead of the window ever showing.
let callWindowMinimized = false;

function createCallWindow(data) {
  callDebugLog(`createCallWindow called, data=${JSON.stringify(data)}, existingWindow=${!!(callWindowRef && !callWindowRef.isDestroyed())}`);
  if (callWindowRef && !callWindowRef.isDestroyed()) {
    callWindowRef.webContents.send('call-data', data);
    if (callWindowMinimized) { callWindowRef.restore(); callWindowMinimized = false; }
    callWindowRef.focus();
    return callWindowRef;
  }

  callWindowMinimized = false;

  callWindowRef = new BrowserWindow({
    width: 340,
    height: 560,
    frame: false,
    transparent: true,
    alwaysOnTop: true,
    resizable: false,
    minimizable: true,
    maximizable: false,
    center: true,
    title: 'Звонок',
    webPreferences: {
      nodeIntegration: true,
      contextIsolation: false,
    },
  });

  callDebugLog('BrowserWindow created, loading call.html');
  callWindowRef.loadFile(path.join(__dirname, 'call.html'));
  callWindowRef.webContents.on('did-fail-load', (_e, code, desc) => {
    callDebugLog(`call.html did-fail-load: code=${code} desc=${desc}`);
  });
  callWindowRef.webContents.on('console-message', (_e, level, message) => {
    callDebugLog(`call.html console[${level}]: ${message}`);
  });

  callWindowRef.once('ready-to-show', () => {
    callDebugLog('ready-to-show fired, calling show()+focus()');
    callWindowRef.show();
    // Without an explicit focus, this frameless/transparent/alwaysOnTop window can
    // come up never truly activated — Windows then sometimes reports isMinimized()
    // as true for it immediately, which the island-update handler below reads as
    // "user minimized it" and forwards straight to the island despite the window
    // never having been visibly minimized by anyone.
    callWindowRef.focus();
    callWindowRef.webContents.send('call-data', data);
    callDebugLog(`after show(): isVisible=${callWindowRef.isVisible()} isMinimized=${callWindowRef.isMinimized()} isFocused=${callWindowRef.isFocused()}`);
  });

  // When minimized → show island in main window
  callWindowRef.on('minimize', () => {
    callDebugLog('native "minimize" event fired');
    callWindowMinimized = true;
    if (mainWindowRef && !mainWindowRef.isDestroyed()) {
      mainWindowRef.webContents.send('call:island-update', {
        state: (data && data._currentCallState) || 'ringing-in',
        callerName: data ? data.callerName : '',
        callerInitials: data ? data.callerInitials : '?',
        callType: data ? data.callType : 'audio',
        timer: null,
      });
    }
  });

  // When restored → hide island
  callWindowRef.on('restore', () => {
    callWindowMinimized = false;
    if (mainWindowRef && !mainWindowRef.isDestroyed()) {
      mainWindowRef.webContents.send('call:island-update', { state: null });
    }
  });

  callWindowRef.on('closed', () => {
    callWindowRef = null;
    callWindowMinimized = false;
    if (mainWindowRef && !mainWindowRef.isDestroyed()) {
      mainWindowRef.webContents.send('call:island-update', { state: null });
    }
  });

  return callWindowRef;
}

// Restore/focus an existing call window without resetting its UI state (unlike
// createCallWindow's existing-window branch, which always re-sends 'call-data'
// and resets call.html back to the ringing screen).
ipcMain.on('call:restore', () => {
  if (callWindowRef && !callWindowRef.isDestroyed()) {
    if (callWindowMinimized) { callWindowRef.restore(); callWindowMinimized = false; }
    callWindowRef.focus();
  }
});

ipcMain.handle('call:open', (_event, data) => {
  callDebugLog(`ipcMain 'call:open' received`);
  createCallWindow(data);
  return true;
});

// ── Windows taskbar overlay badge (unread chat count) ──────────────────────────
// nativeImage has no text/shape drawing API, so the badge is rendered by a tiny
// hidden BrowserWindow (plain HTML circle+number) and captured as a bitmap —
// reused across updates rather than recreated per count.
let badgeWindow = null;
let badgeRenderQueue = Promise.resolve();
let lastBadgeCount = -1;

async function ensureBadgeWindow() {
  if (badgeWindow && !badgeWindow.isDestroyed()) return badgeWindow;
  badgeWindow = new BrowserWindow({
    width: 32,
    height: 32,
    show: false,
    frame: false,
    transparent: true,
    skipTaskbar: true,
    webPreferences: { offscreen: false },
  });
  const html = `<!DOCTYPE html><html><head><style>
    html,body{margin:0;width:32px;height:32px;background:transparent;overflow:hidden}
    #b{width:32px;height:32px;border-radius:50%;background:#ff3b30;display:flex;
       align-items:center;justify-content:center;font:700 16px -apple-system,'Segoe UI',sans-serif;
       color:#fff;box-shadow:0 0 0 2px rgba(0,0,0,.15)}
  </style></head><body><div id="b"></div></body></html>`;
  await badgeWindow.loadURL('data:text/html;charset=utf-8,' + encodeURIComponent(html));
  return badgeWindow;
}

async function setBadgeCount(count) {
  if (process.platform !== 'win32') return; // setOverlayIcon is Windows-only
  const n = Number.isFinite(count) ? Math.max(0, Math.floor(count)) : 0;
  // Serialize: capturePage() on the same hidden window from overlapping calls
  // (badge updates can fire in quick succession) would race on its DOM content.
  badgeRenderQueue = badgeRenderQueue.then(async () => {
    if (n === lastBadgeCount) return;
    // Запоминаем только ПОСЛЕ того, как оверлей реально применён: иначе при
    // отсутствующем окне счётчик считался бы уже нарисованным, и следующий
    // такой же запрос отсеялся бы проверкой выше — бейдж застревал бы в
    // старом состоянии до тех пор, пока число не изменится на другое.
    if (!mainWindowRef || mainWindowRef.isDestroyed()) return;
    lastBadgeCount = n;
    if (n <= 0) {
      mainWindowRef.setOverlayIcon(null, '');
      return;
    }
    try {
      const win = await ensureBadgeWindow();
      const label = n > 99 ? '99+' : String(n);
      const fontSize = label.length > 2 ? 10 : label.length > 1 ? 13 : 16;
      await win.webContents.executeJavaScript(
        `document.getElementById('b').textContent = ${JSON.stringify(label)};` +
        `document.getElementById('b').style.fontSize = '${fontSize}px';`
      );
      const image = await win.webContents.capturePage({ x: 0, y: 0, width: 32, height: 32 });
      mainWindowRef.setOverlayIcon(image, `${n} непрочитанных чатов`);
    } catch (err) {
      console.error('[badge] failed to render overlay icon:', err);
    }
  }).catch((err) => console.error('[badge] queue error:', err));
}

