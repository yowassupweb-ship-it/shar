// Установка вынесена из обработчика кнопки: её же запускает клик по
// уведомлению о новой версии.
function installUpdateNow() {
  if (isInstallingUpdate) return;
  isInstallingUpdate = true;
  console.log('Manual update installation requested');
  callDebugLog('[updater] manual installation requested');

  // The stock NSIS progress window (grey, with a 16-colour icon) looked like a
  // foreign installer, and our Electron splash dies with this process.  A small
  // branded window in its own process stays up while NSIS installs silently and
  // closes itself once the new version starts.  The main window stays on screen
  // until that window has painted, so the click never lands on an empty desktop.
  const splashHandle = { process: null, cancelPath: null };
  void launchUpdateSplash(splashHandle).then((splashShown) => {
    callDebugLog(`[updater] install splash ${splashShown ? 'shown, installing silently' : 'unavailable, using NSIS window'}`);
    if (mainWindowRef && !mainWindowRef.isDestroyed()) mainWindowRef.hide();

    const failInstall = (message, error) => {
      isInstallingUpdate = false;
      console.error(message, error || '');
      // The splash is not our child any more (see launchUpdateSplash): ask it to close.
      try { if (splashHandle.cancelPath) fs.writeFileSync(splashHandle.cancelPath, 'cancel'); } catch {}
      if (mainWindowRef && !mainWindowRef.isDestroyed()) mainWindowRef.show();
      sendUpdaterStatus({ state: 'error', message: 'Не удалось установить обновление автоматически' });
    };

    // If quitAndInstall actually works the process is gone before this fires, so it's
    // a no-op on the happy path. If it silently fails (was seen with no console output
    // and no thrown error at all), this unsticks the flag, brings the window back and
    // tells the renderer, instead of every future click doing nothing forever.
    const stuckTimer = setTimeout(() => {
      failInstall('[updater] quitAndInstall did not quit the app within 5s — treating as failed');
    }, 5000);

    try {
      autoUpdater.quitAndInstall(splashShown, true);
    } catch (error) {
      clearTimeout(stuckTimer);
      failInstall('Failed to install update:', error);
    }
  });
}

// Starts update-splash.ps1 as a detached process and resolves true once its
// window has painted (it writes a marker file), false if it could not start.
function launchUpdateSplash(handle) {
  return new Promise((resolve) => {
    if (process.platform !== 'win32') { resolve(false); return; }
    let settled = false;
    const finish = (value) => { if (!settled) { settled = true; resolve(value); } };
    try {
      // PowerShell cannot read inside app.asar, so the script and logo go to temp.
      const dir = path.join(app.getPath('temp'), 'shar-update-splash');
      fs.mkdirSync(dir, { recursive: true });
      const scriptPath = path.join(dir, 'update-splash.ps1');
      const logoPath = path.join(dir, 'logo.png');
      fs.writeFileSync(scriptPath, fs.readFileSync(path.join(__dirname, 'update-splash.ps1')));
      fs.writeFileSync(logoPath, fs.readFileSync(path.join(__dirname, 'icon.png')));
      const readyPath = path.join(dir, `ready-${process.pid}-${Date.now()}`);
      const powershell = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe');
      const cancelPath = path.join(dir, `cancel-${process.pid}-${Date.now()}`);
      handle.cancelPath = cancelPath;
      // The splash must outlive this process, and no direct spawn does (both measured):
      //  - detached: true is DETACHED_PROCESS — powershell.exe gets no console and
      //    exits in ~0.1 s without a window;
      //  - attached, libuv puts the child in its kill-on-close job object, so the
      //    splash died the moment the app quit for the update and Shar looked dead
      //    for the whole ~2 minute install.
      // That job allows silent breakaway: a short-lived launcher starts the splash
      // with Start-Process, the grandchild is outside the job and survives the quit.
      const psQuote = (value) => `'${String(value).replace(/'/g, "''")}'`;
      const splashArgs = [
        '-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-STA', '-WindowStyle', 'Hidden',
        '-File', `"${scriptPath}"`, '-LogoPath', `"${logoPath}"`, '-ReadyPath', `"${readyPath}"`, '-CancelPath', `"${cancelPath}"`,
      ];
      const launcher = `Start-Process -FilePath ${psQuote(powershell)} -WindowStyle Hidden -ArgumentList @(${splashArgs.map(psQuote).join(',')})`;
      const child = spawn(powershell, ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-Command', launcher], { stdio: 'ignore', windowsHide: true });
      handle.process = child;
      child.once('error', (err) => { callDebugLog(`[updater] install splash failed to start: ${err}`); finish(false); });
      // The launcher exits right after Start-Process; only a failing exit means no splash.
      child.once('exit', (code) => {
        if (code) { callDebugLog(`[updater] install splash launcher exited with ${code}`); finish(false); }
      });
      child.unref();

      const startedAt = Date.now();
      const poll = setInterval(() => {
        if (settled) { clearInterval(poll); return; }
        if (fs.existsSync(readyPath)) {
          clearInterval(poll);
          try { fs.unlinkSync(readyPath); } catch {}
          finish(true);
          return;
        }
        if (Date.now() - startedAt > 6000) {
          clearInterval(poll);
          // A splash that shows up late must not sit over the visible NSIS fallback.
          try { fs.writeFileSync(cancelPath, 'cancel'); } catch {}
          finish(false);
        }
      }, 100);
    } catch (err) {
      callDebugLog(`[updater] install splash failed to start: ${err}`);
      finish(false);
    }
  });
}

