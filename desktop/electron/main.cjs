// A reconnect can replay the final websocket frame. Keep message identity here
// (outside the renderer) so it cannot make two native notification cards.
const mainRealtimeSeenMessageKeys = new Map();
const MAIN_REALTIME_DEDUPE_MS = 5 * 60 * 1000;

function claimMainRealtimeMessage(key) {
  const now = Date.now();
  for (const [knownKey, createdAt] of mainRealtimeSeenMessageKeys) {
    if (now - createdAt > MAIN_REALTIME_DEDUPE_MS) mainRealtimeSeenMessageKeys.delete(knownKey);
  }
  if (mainRealtimeSeenMessageKeys.has(key)) return false;
  mainRealtimeSeenMessageKeys.set(key, now);
  return true;
}

// Every message card — from the main-process socket or from the renderer over
// IPC — passes this one gate.  Per-path guards were not enough: each path only
// knew its own history, so two of them could still stack identical cards.
// The id key covers the normal case; the short text key catches the same
// message arriving under a different id (or none) from the other path.
const recentMessageCards = new Map();
const MESSAGE_CARD_ID_TTL_MS = 5 * 60 * 1000;
const MESSAGE_CARD_TEXT_TTL_MS = 10 * 1000;

function claimMessageCard(data) {
  const now = Date.now();
  for (const [key, expiresAt] of recentMessageCards) {
    if (expiresAt <= now) recentMessageCards.delete(key);
  }
  // The renderer lifts chatId out of its URL, still percent-encoded; the socket
  // path has it raw.  Compare the same form or the keys never meet.
  let chatId = String(data?.chatId || '').trim();
  try { chatId = decodeURIComponent(chatId); } catch {}
  const messageId = String(data?.messageId || '').trim();
  const text = String(data?.message || '').replace(/\s+/g, ' ').trim();
  const keys = [];
  if (chatId && messageId) keys.push([`id:${chatId}:${messageId}`, MESSAGE_CARD_ID_TTL_MS]);
  keys.push([`text:${chatId}:${text}`, MESSAGE_CARD_TEXT_TTL_MS]);
  const source = String(data?.source || 'unknown');
  const duplicate = keys.find(([key]) => recentMessageCards.has(key));
  if (duplicate) {
    callDebugLog(`[notify] duplicate dropped source=${source} chat=${chatId} message=${messageId || '-'} by=${duplicate[0].split(':')[0]}`);
    return false;
  }
  for (const [key, ttl] of keys) recentMessageCards.set(key, now + ttl);
  callDebugLog(`[notify] card source=${source} chat=${chatId} message=${messageId || '-'}`);
  return true;
}

async function getLocalSessionCookieHeader() {
  const remoteBase = resolveBackendUrl().replace(/\/+$/, '');
  const cookies = await session.defaultSession.cookies.get({ url: bundledFrontendUrl || remoteBase });
  return cookies.map((c) => `${c.name}=${c.value}`).join('; ');
}

function stopMainRealtime() {
  mainRealtimeStopped = true;
  mainRealtimeGeneration += 1;
  if (mainRealtimeReconnectTimer) clearTimeout(mainRealtimeReconnectTimer);
  mainRealtimeReconnectTimer = null;
  try { mainRealtimeWs?.close(); } catch {}
  mainRealtimeWs = null;
  mainRealtimeUserId = null;
}

function scheduleMainRealtimeReconnect(delayMs = 1000) {
  if (mainRealtimeStopped || !mainRealtimeUserId || mainRealtimeReconnectTimer) return;
  mainRealtimeReconnectTimer = setTimeout(() => {
    mainRealtimeReconnectTimer = null;
    void connectMainRealtime();
  }, delayMs);
}

async function connectMainRealtime() {
  if (mainRealtimeStopped || !mainRealtimeUserId) return false;
  const generation = mainRealtimeGeneration;
  try {
    const cookieHeader = await getLocalSessionCookieHeader();
    if (generation !== mainRealtimeGeneration || mainRealtimeStopped) return false;
    if (mainRealtimeWs && (mainRealtimeWs.readyState === WebSocket.OPEN || mainRealtimeWs.readyState === WebSocket.CONNECTING)) return true;
    if (!cookieHeader) { scheduleMainRealtimeReconnect(); return false; }
    const remoteBase = resolveBackendUrl().replace(/\/+$/, '');
    const targetUrl = `${remoteBase.replace(/^http/, 'ws')}/api/ws/${encodeURIComponent(mainRealtimeUserId)}`;
    const ws = new WebSocket(targetUrl, { headers: { Cookie: cookieHeader } });
    mainRealtimeWs = ws;
    ws.on('open', () => callDebugLog('[main-realtime] connected'));
    ws.on('message', (raw) => {
      // A replaced socket can still deliver its last frames; only the current one speaks.
      if (mainRealtimeWs !== ws) return;
      let event;
      try { event = JSON.parse(String(raw)); } catch { return; }
      if (event?.type !== 'new_message' || !event?.chatId) return;
      const message = event.message || {};
      const authorId = String(message.authorId || message.author_id || '');
      // Свои сообщения карточкой не показываем — кроме системных уведомлений
      // (напоминание о событии и т.п.): они записываются от имени самого человека.
      const isSystemNotice = Boolean(message.isSystemMessage || message.is_system_message || message.notificationType || message.notification_type);
      if (authorId && authorId === String(mainRealtimeUserId) && !isSystemNotice) return;
      const win = mainWindowRef;
      if (!win || win.isDestroyed()) return;
      const chatId = String(event.chatId);
      const messageId = String(message.id || message.messageId || message.message_id || '').trim();
      if (!messageId || !claimMainRealtimeMessage(`msg:${chatId}:${messageId}`)) return;
      const authorName = String(message.authorName || message.author_name || message.senderName || 'Новое сообщение');
      const avatar = String(authorAvatarCache.get(authorId) || message.authorAvatar || message.author_avatar || '').trim()
        || `https://api.dicebear.com/9.x/thumbs/svg?seed=${encodeURIComponent(authorName || authorId || 'user')}&backgroundColor=b6e3f4,c0aede,d1d4f9,ffd5dc,ffdfbf`;
      win.webContents.send('realtime:notification-poke', { chatId, at: Date.now() });
      const onScreen = win.isVisible() && !win.isMinimized();
      const windowFocused = win.isFocused();
      const rendererFocused = rendererContext.focused;
      const inThisChat = rendererContext.activeChatId === chatId;
      const inputAgoMs = rendererContext.lastInputAt ? Date.now() - rendererContext.lastInputAt : Infinity;
      const attending = onScreen && (windowFocused || rendererFocused);
      callDebugLog(`[notify] main-ws chat=${chatId} message=${messageId} onScreen=${onScreen} windowFocused=${windowFocused} rendererFocused=${rendererFocused} inThisChat=${inThisChat} inputAgo=${Number.isFinite(inputAgoMs) ? Math.round(inputAgoMs / 1000) + 's' : '-'} -> ${attending ? 'skip' : 'show'}`);
      if (!attending) {
        // The renderer may be throttled while nobody is looking, so the badge
        // moves here too — but by CHATS (the renderer's unit), on top of the
        // renderer's own last count, and only while unattended.
        mainPendingUnreadChats.add(chatId);
        setBadgeCount(rendererBadgeCount + mainPendingUnreadChats.size);
        createNotificationWindow({ title: authorName, senderName: authorName, message: String(message.content || 'Вложение'), avatar, chatId, messageId, source: 'main-ws', url: `/account?tab=messages&chat=${encodeURIComponent(chatId)}`, kind: 'message', timestamp: Date.now() }, win);
      }
    });
    // Only the current socket may trigger a reconnect.  An old socket closed by
    // stopMainRealtime() used to schedule one after the renderer had already
    // re-registered, leaving an extra live socket behind on every restart.
    ws.on('close', (code) => {
      if (mainRealtimeWs !== ws) return;
      mainRealtimeWs = null;
      // 1008: the server does not recognise the session. Retrying every second only
      // hammers it (hundreds of rejections per 10 minutes) — back off.
      scheduleMainRealtimeReconnect(code === 1008 ? 30000 : 1000);
    });
    ws.on('error', () => { try { ws.close(); } catch {} });
    return true;
  } catch (error) {
    callDebugLog(`[main-realtime] connect failed: ${error}`);
    scheduleMainRealtimeReconnect();
    return false;
  }
}

function startMainRealtime(userId) {
  const nextUserId = String(userId || '').trim();
  if (!nextUserId) return false;
  if (mainRealtimeUserId !== nextUserId) stopMainRealtime();
  mainRealtimeStopped = false;
  mainRealtimeUserId = nextUserId;
  if (!mainRealtimeWs || mainRealtimeWs.readyState === WebSocket.CLOSED) void connectMainRealtime();
  return true;
}

async function startWsProxy() {
  if (wsProxyPort) return wsProxyPort;
  const port = await reserveLocalPort();
  const server = http.createServer();
  const wss = new WebSocket.Server({ server });

  wss.on('connection', async (clientWs, req) => {
    const remoteBase = resolveBackendUrl().replace(/\/+$/, '');
    const targetUrl = remoteBase.replace(/^http/, 'ws') + req.url;

    // The session cookie was set via the local proxy API routes (see e.g.
    // /api/auth/login/route.ts forwarding the backend's Set-Cookie verbatim) — that
    // response came FROM the bundled UI's local origin (bundledFrontendUrl), so the
    // browser's cookie jar scoped it there, not to remoteBase. A cookie with
    // Domain=<real domain> would be rejected outright as cross-origin, and one with
    // no Domain attribute becomes host-only for whichever origin actually served the
    // response — either way remoteBase never has it. Reading remoteBase here always
    // returned nothing, so the upstream leg connected with no session at all and the
    // backend closed it almost immediately — the actual cause of the reconnect loop.
    let cookieHeader = '';
    try {
      const cookieLookupBase = bundledFrontendUrl || remoteBase;
      const cookies = await session.defaultSession.cookies.get({ url: cookieLookupBase });
      cookieHeader = cookies.map((c) => `${c.name}=${c.value}`).join('; ');
      callDebugLog(`[ws-proxy] cookieLookupBase=${cookieLookupBase} cookieCount=${cookies.length} names=${cookies.map((c) => c.name).join(',')}`);
    } catch (err) {
      console.error('[ws-proxy] Failed to read cookies:', err);
      callDebugLog(`[ws-proxy] cookie lookup threw: ${err}`);
    }

    const upstream = new WebSocket(targetUrl, { headers: { Cookie: cookieHeader } });
    const pending = [];
    let upstreamOpen = false;
    const connId = Date.now() + '-' + Math.random().toString(36).slice(2, 7);
    callDebugLog(`[ws-proxy ${connId}] client connected, opening upstream ${targetUrl}`);

    upstream.on('open', () => {
      upstreamOpen = true;
      callDebugLog(`[ws-proxy ${connId}] upstream open`);
      for (const msg of pending) upstream.send(msg.data, { binary: msg.isBinary });
      pending.length = 0;
    });
    // ws@8 отдаёт любой кадр как Buffer, и send(Buffer) без флага уходит
    // БИНАРНЫМ кадром. Страница получала вместо текста Blob, JSON.parse падал,
    // и каждое событие сокета (new_message, hello, read…) молча терялось, хотя
    // пинги держали соединение «живым». Тип кадра передаём как есть.
    upstream.on('message', (data, isBinary) => {
      if (clientWs.readyState === WebSocket.OPEN) clientWs.send(data, { binary: isBinary });
    });
    clientWs.on('message', (data, isBinary) => {
      if (upstreamOpen) upstream.send(data, { binary: isBinary });
      else pending.push({ data, isBinary });
    });

    const closeBoth = (origin, code, reason) => {
      callDebugLog(`[ws-proxy ${connId}] closeBoth triggered by ${origin}, code=${code}, reason=${reason}`);
      try { clientWs.close(); } catch {}
      try { upstream.close(); } catch {}
    };
    upstream.on('close', (code, reason) => closeBoth('upstream-close', code, reason));
    upstream.on('error', (err) => closeBoth('upstream-error', '', String(err)));
    clientWs.on('close', (code, reason) => closeBoth('client-close', code, reason));
    clientWs.on('error', (err) => closeBoth('client-error', '', String(err)));
  });

  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(port, '127.0.0.1', () => resolve());
  });

  wsProxyPort = port;
  process.env.SHAR_WS_PROXY_PORT = String(port);
  return port;
}

async function startBundledFrontend() {
  if (frontendServer && !frontendServer.killed && bundledFrontendUrl) {
    return bundledFrontendUrl;
  }

  const webRoot = app.isPackaged
    ? path.join(process.resourcesPath, 'web')
    : path.join(__dirname, '..', 'web');
  const serverEntry = path.join(webRoot, 'server.js');
  if (!fs.existsSync(serverEntry)) return null;

  const port = await reserveFrontendPort();
  const localUrl = `http://127.0.0.1:${port}`;
  frontendServer = spawn(process.execPath, [serverEntry], {
    cwd: webRoot,
    windowsHide: true,
    stdio: 'ignore',
    env: {
      ...process.env,
      ELECTRON_RUN_AS_NODE: '1',
      NODE_ENV: 'production',
      HOSTNAME: '127.0.0.1',
      PORT: String(port),
      // Node's fetch (undici) tries AAAA (IPv6) first by default, and on a machine
      // with IPv6 either unsupported or dead-ended (common on Windows/office
      // networks), each attempt burns its own multi-second timeout before falling
      // back to the working IPv4 address — on EVERY outbound request this server
      // proxies to the real backend. That's what showed up client-side as
      // "[TEST-CHAT] Messages/Chats request timed out" repeatedly, with the whole
      // desktop app looking like it just doesn't update until manually poked.
      NODE_OPTIONS: `${process.env.NODE_OPTIONS || ''} --dns-result-order=ipv4first`.trim(),
      BACKEND_URL: resolveBackendUrl(),
    },
  });

  frontendServer.once('exit', () => {
    frontendServer = null;
    bundledFrontendUrl = null;
  });

  if (await waitForFrontend(localUrl)) {
    bundledFrontendUrl = localUrl;
    return localUrl;
  }

  if (frontendServer && !frontendServer.killed) frontendServer.kill();
  frontendServer = null;
  bundledFrontendUrl = null;
  return null;
}

function stopBundledFrontend() {
  if (frontendServer && !frontendServer.killed) frontendServer.kill();
  frontendServer = null;
  bundledFrontendUrl = null;
}

