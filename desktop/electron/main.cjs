function ensureAutoLaunchEnabled() {
  if (IS_BETA || !app.isPackaged || process.platform !== 'win32') return;

  try {
    if (!getAutoLaunchPreference()) return;

    const current = app.getLoginItemSettings();
    if (current.openAtLogin) return;

    app.setLoginItemSettings({
      openAtLogin: true,
      path: process.execPath,
      args: [],
    });
    callDebugLog('[startup] Windows auto-launch enabled');
  } catch (err) {
    console.error('[startup] Failed to enable auto-launch:', err);
    callDebugLog(`[startup] auto-launch failed: ${err?.message || err}`);
  }
}

function getAutoLaunchPreferencePath() {
  return path.join(app.getPath('userData'), 'startup-preferences.json');
}

function getAutoLaunchPreference() {
  try {
    const raw = fs.readFileSync(getAutoLaunchPreferencePath(), 'utf8');
    const parsed = JSON.parse(raw);
    if (typeof parsed.openAtLogin === 'boolean') return parsed.openAtLogin;
  } catch {}

  return true;
}

function setAutoLaunchPreference(openAtLogin) {
  const enabled = Boolean(openAtLogin);
  try {
    fs.mkdirSync(app.getPath('userData'), { recursive: true });
    fs.writeFileSync(getAutoLaunchPreferencePath(), JSON.stringify({ openAtLogin: enabled }), 'utf8');
  } catch (err) {
    callDebugLog(`[startup] preference save failed: ${err?.message || err}`);
  }

  if (process.platform === 'win32') {
    app.setLoginItemSettings({
      openAtLogin: enabled,
      path: process.execPath,
      args: [],
    });
  }

  return enabled;
}

// Без этого лока каждый повторный запуск (двойной клик по ярлыку, автозапуск и т.п.)
// поднимал ещё один полноценный процесс — свой Electron + свой bundled Next-сервер —
// одновременно с уже открытым. Несколько таких процессов конкурировали за CPU/IO,
// отсюда и открытие по 30+ секунд. Второй запуск теперь просто поднимает уже
// открытое окно вместо старта нового процесса.
const gotSingleInstanceLock = app.requestSingleInstanceLock();
if (!gotSingleInstanceLock) {
  app.quit();
} else {
  app.on('second-instance', () => {
    if (mainWindowRef && !mainWindowRef.isDestroyed()) {
      if (mainWindowRef.isMinimized()) mainWindowRef.restore();
      mainWindowRef.show();
      mainWindowRef.focus();
    }
  });
}

// Discord-style: never open the main window on a version the user is about to be
// upgraded out of. Shows the splash, checks for an update, and — if one downloads
// — installs and relaunches (quitAndInstall) WITHOUT ever calling createWindow in
// this process; the relaunched instance runs this same gate again, finds nothing
// pending, and proceeds normally. Previously the update check fired 3s *after* the
// main window was already up, so every update was seen only on the *next* cold
// launch — this makes the currently-running instance never launch on stale code.
function waitForUpdateOrProceed() {
  return new Promise((resolve) => {
    if (!app.isPackaged || IS_BETA) { resolve(); return; }

    let settled = false;
    const proceed = () => { if (!settled) { settled = true; resolve(); } };

    autoUpdater.once('update-not-available', proceed);
    autoUpdater.once('error', proceed);
    autoUpdater.once('update-downloaded', () => {
      // Downloading is not permission to silently replace the app at startup.
      // Continue into the current version and offer a visible, explicit restart.
      proceed();
    });
    // The check itself (not the download, which can legitimately take longer and
    // is covered by its own progress UI) shouldn't be able to strand someone on
    // the splash indefinitely if the update server is unreachable.
    setTimeout(proceed, 20000);

    autoUpdater.checkForUpdates().catch(proceed);
  });
}

// Медиа-разрешения и захват экрана для звонков.
//
// Явный обработчик запросов вместо поведения по умолчанию: звонок живёт в
// главном окне (useCallSession), микрофон берётся через getUserMedia — и отказ
// здесь выглядит как «звонок идёт, а меня не слышно», без единого следа в
// интерфейсе.
//
// getDisplayMedia в Electron с 17-й версии не работает ВООБЩЕ, пока не задан
// setDisplayMediaRequestHandler: демонстрация экрана внутри звонка молча
// отваливалась именно поэтому. Отдаём экран целиком — выбор источника в нашем
// интерфейсе всё равно не предусмотрен.
function setupMediaPermissions() {
  const ses = session.defaultSession;
  const ALLOWED = new Set([
    'media', 'audioCapture', 'videoCapture', 'display-capture',
    'notifications', 'clipboard-sanitized-write',
  ]);

  ses.setPermissionRequestHandler((_wc, permission, callback) => {
    const granted = ALLOWED.has(permission);
    if (!granted) callDebugLog(`[calls] разрешение "${permission}" отклонено`);
    callback(granted);
  });
  // Синхронная проверка — по ней Chromium решает, показывать ли устройства и
  // пускать ли getUserMedia без отдельного запроса.
  ses.setPermissionCheckHandler((_wc, permission) => ALLOWED.has(permission));

  ses.setDisplayMediaRequestHandler((_request, callback) => {
    desktopCapturer.getSources({ types: ['screen', 'window'] }).then((sources) => {
      const screen = sources.find((s) => String(s.id).startsWith('screen:')) || sources[0];
      if (!screen) { callback(); return; }
      callback({ video: screen, audio: 'loopback' });
    }).catch((err) => {
      callDebugLog(`[calls] getDisplayMedia: не удалось получить источники: ${err}`);
      callback();
    });
  });
}

