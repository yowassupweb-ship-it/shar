function reserveLocalPort() {
  return new Promise((resolve, reject) => {
    const server = nodeNet.createServer();
    server.unref();
    server.once('error', reject);
    server.listen(0, '127.0.0.1', () => {
      const address = server.address();
      const port = typeof address === 'object' && address ? address.port : 0;
      server.close((error) => error ? reject(error) : resolve(port));
    });
  });
}

// The bundled UI's own origin (http://127.0.0.1:PORT) is where localStorage,
// IndexedDB and Service Worker registrations all live — and those are scoped by
// origin INCLUDING the port. A random port every launch (via reserveLocalPort)
// meant each launch got its own empty localStorage, and app/page.tsx's root
// redirect gates on localStorage.isAuthenticated alone — so every single launch
// bounced to /login even though the real (cookie-based) session was still valid.
// Try this fixed port first so the origin — and everything stored under it —
// stays the same across launches; only fall back to a random one if it's taken
// (e.g. a second copy somehow running despite the single-instance lock).
const PREFERRED_FRONTEND_PORT = IS_BETA ? 47822 : 47821;
async function reserveFrontendPort() {
  try {
    await new Promise((resolve, reject) => {
      const server = nodeNet.createServer();
      server.unref();
      server.once('error', reject);
      server.listen(PREFERRED_FRONTEND_PORT, '127.0.0.1', () => {
        server.close((error) => error ? reject(error) : resolve());
      });
    });
    return PREFERRED_FRONTEND_PORT;
  } catch {
    return reserveLocalPort();
  }
}

async function waitForFrontend(url, timeoutMs = 30000) {
  const startedAt = Date.now();
  while (Date.now() - startedAt < timeoutMs) {
    try {
      const response = await net.fetch(url);
      if (response.ok || response.status === 307 || response.status === 308) return true;
    } catch {}
    await new Promise(resolve => setTimeout(resolve, 250));
  }
  return false;
}

