// Flat, deduplicated list — used by the plain grid picker (reactions) and as the
// fallback "search across everything" source for the categorized picker.
export const ALL_EMOJI_ITEMS: EmojiItem[] = (() => {
  const seen = new Set<string>();
  const items: EmojiItem[] = [];
  for (const cat of EMOJI_CATEGORIES) {
    for (const item of cat.items) {
      if (seen.has(item.v)) continue;
      seen.add(item.v);
      items.push(item);
    }
  }
  return items;
})();

export function searchEmoji(query: string, source: EmojiItem[] = ALL_EMOJI_ITEMS): EmojiItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return source;
  return source.filter(i => i.v.includes(q) || i.k.toLowerCase().includes(q));
}

// Word → emoji index for the composer's "suggest as you type" popup — keyed on
// exact whole-word matches (not substrings, unlike searchEmoji above), so typing
// "смех" mid-sentence suggests 😂/🤣 the moment that whole word is complete, without
// firing on partial words like "смехотвор...".
const WORD_INDEX: Map<string, EmojiItem[]> = (() => {
  const map = new Map<string, EmojiItem[]>();
  for (const item of ALL_EMOJI_ITEMS) {
    for (const word of item.k.toLowerCase().split(/\s+/)) {
      if (!word) continue;
      const list = map.get(word) ?? [];
      list.push(item);
      map.set(word, list);
    }
  }
  return map;
})();

// All distinct keywords, longest first — used by the fuzzy pass below so a shorter
// keyword's suggestions don't crowd out a longer, more-specific one that also
// matches (e.g. typing "смеш" should prioritize "смешно" over any short unrelated
// word that happens to also be ≥70% covered).
const ALL_WORDS: string[] = Array.from(WORD_INDEX.keys()).sort((a, b) => b.length - a.length);

export function matchEmojiByWord(word: string): EmojiItem[] {
  const w = word.trim().toLowerCase();
  if (w.length < 2) return [];

  const exact = WORD_INDEX.get(w);
  if (exact) return exact;

  // Fuzzy pass: suggest while still typing, once what's typed so far is a prefix of
  // a real keyword AND covers at least 70% of that keyword's length — e.g. "печата"
  // (6 chars) covers 6/7 ≈ 86% of "печатаю", so the suggestion appears before the
  // word is even finished. A word can match several keywords (returns all of them,
  // deduplicated by emoji).
  const seen = new Set<string>();
  const results: EmojiItem[] = [];
  for (const candidate of ALL_WORDS) {
    if (candidate.length < w.length) continue; // typed text can't out-cover a shorter real word
    if (w.length / candidate.length < 0.7) continue;
    if (!candidate.startsWith(w)) continue;
    for (const item of WORD_INDEX.get(candidate) ?? []) {
      if (seen.has(item.v)) continue;
      seen.add(item.v);
      results.push(item);
    }
  }
  return results;
}
